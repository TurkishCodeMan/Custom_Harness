import React, { useEffect } from 'react'

export type ReactNode = any

// --- 1. Button Component ---
export interface ButtonProps extends React.ButtonHTMLAttributes<HTMLButtonElement> {
  variant?: 'primary' | 'secondary' | 'danger' | 'ghost' | 'icon'
  size?: 'sm' | 'md' | 'lg'
  children?: any
}

export function Button({ variant = 'secondary', size = 'md', className = '', children, ...props }: ButtonProps) {
  const baseClass = `btn btn-${variant} btn-${size} ${className}`.trim()
  return (
    <button className={baseClass} {...props}>
      {children}
    </button>
  )
}

// --- 2. Badge Component ---
export interface BadgeProps {
  variant?: 'default' | 'success' | 'warning' | 'purple' | 'cyan' | 'danger'
  children: any
  className?: string
  icon?: any
}

export function Badge({ variant = 'default', children, className = '', icon }: BadgeProps) {
  return (
    <span className={`badge badge-${variant} ${className}`.trim()}>
      {icon && <span className="badge-icon">{icon}</span>}
      <span>{children}</span>
    </span>
  )
}

// --- 3. Modal Dialog Component ---
export interface ModalProps {
  isOpen: boolean
  onClose: () => void
  title: any
  children: any
  footer?: any
  maxWidth?: string
}

export function Modal({ isOpen, onClose, title, children, footer, maxWidth = '650px' }: ModalProps) {
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape' && isOpen) onClose()
    }
    window.addEventListener('keydown', handleKeyDown)
    return () => window.removeEventListener('keydown', handleKeyDown)
  }, [isOpen, onClose])

  if (!isOpen) return null

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div
        className="modal-card"
        style={{ maxWidth }}
        onClick={(e) => e.stopPropagation()}
      >
        <div className="modal-header">
          <h3 className="modal-title">{title}</h3>
          <button className="btn-close" onClick={onClose} title="Kapat">
            &times;
          </button>
        </div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-footer">{footer}</div>}
      </div>
    </div>
  )
}

// --- 4. Tooltip Component ---
export interface TooltipProps {
  text: string
  children: ReactNode
}

export function Tooltip({ text, children }: TooltipProps) {
  return (
    <div className="tooltip-container">
      {children}
      <span className="tooltip-bubble">{text}</span>
    </div>
  )
}

